#!/usr/bin/env python3
"""Generate or check Codex/Claude adapters from shared role and skill sources."""

import argparse
import json
from pathlib import Path
import sys

from check_setup import frontmatter


ROOT = Path(__file__).resolve().parents[1]


def expected_adapters(root):
    expected = {}
    tools = json.loads((root / "agents/claude-tools.json").read_text())
    for role in sorted((root / "agents").glob("*.md")):
        data = frontmatter(role)
        body = role.read_text().split("---\n", 2)[2].strip()
        shared = (
            "Read AGENTS.md from the platform root supplied by the orchestrator. "
            "Resolve project paths from that root. Read these skill files before the task:\n"
            + "\n".join(f"- .agents/skills/{name}/SKILL.md" for name in data["skills"])
            + "\n\n" + body + "\n"
        )
        toml = (
            "# Generated by scripts/sync_runtime.py; edit agents/ instead.\n"
            + f"name = {json.dumps(data['name'])}\n"
            + f"description = {json.dumps(data['description'])}\n"
            + f"developer_instructions = {json.dumps(shared)}\n"
        )
        expected[Path(".codex/agents") / f"{role.stem}.toml"] = toml
        header = (
            f"---\nname: {data['name']}\ndescription: {data['description']}\n"
            f"tools: {tools[role.stem]}\nmodel: inherit\nskills:\n"
            + "".join(f"  - {name}\n" for name in data["skills"])
            + "---\n\n<!-- Generated by scripts/sync_runtime.py; edit agents/ instead. -->\n\n"
        )
        expected[Path(".claude/agents") / role.name] = header + shared
    for path in sorted((root / ".agents/skills").rglob("*")):
        if path.is_file():
            expected[Path(".claude/skills") / path.relative_to(root / ".agents/skills")] = path.read_text()
    return expected


def adapter_errors(root):
    expected = expected_adapters(root)
    errors = []
    for relative, content in expected.items():
        path = root / relative
        if not path.is_file():
            errors.append(f"Missing runtime adapter: {relative}")
        elif path.read_text() != content:
            errors.append(f"Stale runtime adapter: {relative}")
    for directory in (".codex/agents", ".claude/agents", ".claude/skills"):
        for path in (root / directory).rglob("*"):
            if path.is_file() and path.relative_to(root) not in expected:
                errors.append(f"Unexpected adapter file (review before removing): {path.relative_to(root)}")
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Report adapter drift without writing")
    args = parser.parse_args()
    if not args.check:
        for relative, content in expected_adapters(ROOT).items():
            path = ROOT / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    errors = adapter_errors(ROOT)
    for error in errors:
        print(f"FAIL: {error}")
    print(f"Runtime adapter check: {len(errors)} error(s)")
    return bool(errors)


if __name__ == "__main__":
    sys.exit(main())
